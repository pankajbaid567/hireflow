"""Rebuild the licensed, bounded Unicode resume fonts (not needed at runtime).

Requires fonttools==4.67.0. Downloads only a pinned official Noto commit and
verifies source hashes from the checked-in manifest on subsequent runs.
"""
from __future__ import annotations
import argparse, base64, hashlib, io, json
from pathlib import Path
import requests
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
COMMIT = 'ffebf8c1ee449e544955a7e813c54f9b73848eac'
BASE = f'https://raw.githubusercontent.com/notofonts/noto-fonts/{COMMIT}'
ASSETS = ROOT / 'assets/fonts'
SPECS = (
    ('latin', 'NotoSans', 'HireFlowSans', '0000-024F,0370-052F,1E00-1EFF,2000-206F,20A0-20CF'),
    ('devanagari', 'NotoSansDevanagari', 'HireFlowDevanagari', '0000-007F,0900-097F,1CD0-1CFF,200C-200D,20B9,A8E0-A8FF'),
)

def digest(data):return hashlib.sha256(data).hexdigest()
def fetch(path):
    response=requests.get(f'{BASE}/{path}',timeout=30);response.raise_for_status();return response.content

def build():
    ASSETS.mkdir(parents=True,exist_ok=True)
    previous=json.loads((ASSETS/'manifest.json').read_text()) if (ASSETS/'manifest.json').exists() else {}
    manifest={'source_commit':COMMIT,'tool':'fonttools 4.67.0','fonts':[]}
    definitions=[]
    for key,family,renamed,ranges in SPECS:
        source_path=f'hinted/ttf/{family}/{family}-Regular.ttf';original=fetch(source_path)
        old=next((item for item in previous.get('fonts',[]) if item['key']==key),None)
        if old and old['source_sha256']!=digest(original):raise ValueError('Pinned source font changed')
        font=TTFont(io.BytesIO(original));options=subset.Options()
        options.layout_features=['*'];options.notdef_outline=True;options.recalc_timestamp=False
        selected=subset.Subsetter(options=options)
        selected.populate(unicodes=subset.parse_unicodes(ranges));selected.subset(font)
        for record in font['name'].names:
            value={1:renamed,2:'Regular',3:f'{renamed}-Regular',4:f'{renamed} Regular',6:f'{renamed}-Regular'}.get(record.nameID)
            if value is not None:record.string=value.encode(record.getEncoding(),errors='strict')
        font.recalcTimestamp=False
        buffer=io.BytesIO();font.save(buffer);data=buffer.getvalue()
        filename=f'{renamed}-Regular.ttf';(ASSETS/filename).write_bytes(data)
        cmap=font.getBestCmap();metrics={str(cp):[font.getGlyphID(glyph),font['hmtx'][glyph][0]] for cp,glyph in cmap.items()}
        h=font['head'];ascent=font['hhea'].ascent;descent=font['hhea'].descent
        definition={'key':key,'name':f'{renamed}-Regular','data':base64.b64encode(data).decode(),'unitsPerEm':h.unitsPerEm,'bbox':[h.xMin,h.yMin,h.xMax,h.yMax],'ascent':ascent,'descent':descent,'metrics':metrics,'advances':[font['hmtx'][glyph][0] for glyph in font.getGlyphOrder()]}
        definitions.append(f'export const {key.upper()}_FONT = '+json.dumps(definition,separators=(',',':'))+' as const;')
        manifest['fonts'].append({'key':key,'filename':filename,'source_url':f'{BASE}/{source_path}','source_sha256':digest(original),'subset_sha256':digest(data),'bytes':len(data),'unicode_ranges':ranges,'glyph_count':len(font.getGlyphOrder())})
    (ASSETS/'OFL.txt').write_bytes(fetch('LICENSE'))
    (ASSETS/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    header='// Generated by scripts/build_resume_fonts.py; do not edit. Noto OFL license: assets/fonts/OFL.txt.\n'
    (ROOT/'cloudflare/src/resume_font_data.ts').write_text(header+'\n'.join(definitions)+'\n')
    print(json.dumps({'fonts':[{k:v for k,v in f.items() if k in ['key','bytes','glyph_count']} for f in manifest['fonts']]}))

if __name__=='__main__':build()
